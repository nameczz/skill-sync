export type TranslationKey = keyof typeof en;
export type TFunction = (key: TranslationKey, params?: Record<string, string | number>) => string;

export function detectBrowserLocale(): Locale {
  if (typeof navigator === "undefined") {
    return "en";
  }

  const languages = navigator.languages?.length ? navigator.languages : [navigator.language];
  return languages.some((language) => language.toLowerCase().startsWith("zh")) ? "zh" : "en";
}

export function readInitialLocale(): Locale {
  if (typeof window === "undefined") {
    return "en";
  }

  const stored = window.localStorage.getItem(localeStorageKey);
  if (stored === "en" || stored === "zh") {
    return stored;
  }

  return detectBrowserLocale();
}

export function makeT(locale: Locale): TFunction {
  return (key, params) => translate(locale, key, params);
}

export function translate(locale: Locale, key: TranslationKey, params: Record<string, string | number> = {}): string {
  const template = (locale === "zh" ? zh[key] : undefined) ?? en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ""));
}

export function documentLanguage(locale: Locale): string {
  return locale === "zh" ? "zh-CN" : "en";
}
